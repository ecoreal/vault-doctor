// Markdown report generation. Pure.

import { CATEGORY_LABEL, ScanResult } from './types';
import { humanSize } from './engine';

export interface ReportOptions {
	vaultName: string;
	maxRowsPerSection: number;
}

export function generateReport(result: ScanResult, opts: ReportOptions): string {
	const { findings, stats } = result;
	const when = new Date().toISOString().replace('T', ' ').slice(0, 19);
	const lines: string[] = [];

	lines.push('# Vault Doctor Report');
	lines.push('');
	lines.push(`> Vault **${opts.vaultName}** · scanned ${when}`);
	lines.push('');

	// Summary
	lines.push('## Summary');
	lines.push('');
	lines.push('| Metric | Value |');
	lines.push('| --- | --- |');
	lines.push(`| Notes | ${stats.notes} |`);
	lines.push(`| Attachments | ${stats.attachments} (${humanSize(stats.totalSize)} total in vault) |`);
	lines.push(`| Links | ${stats.links} (${stats.resolvedLinks} resolve, ${stats.links - stats.resolvedLinks} broken/unresolved) |`);
	const issues = findings.length;
	lines.push(`| Findings | ${issues} |`);
	lines.push('');

	if (issues === 0) {
		lines.push('✅ **All checks passed.** Your vault looks healthy.');
		lines.push('');
	}

	// Group by category
	const byCat = new Map<string, typeof findings>();
	for (const f of findings) {
		const arr = byCat.get(f.category) ?? [];
		arr.push(f);
		byCat.set(f.category, arr);
	}

	for (const [cat, items] of byCat) {
		lines.push(`## ${CATEGORY_LABEL[cat as keyof typeof CATEGORY_LABEL] ?? cat} (${items.length})`);
		lines.push('');
		const shown = items.slice(0, opts.maxRowsPerSection);
		for (const f of shown) {
			const loc = f.link ? ` (line ${f.link.line + 1})` : '';
			lines.push(`- **${f.message}** — [[${f.file}]]${loc}`);
			if (f.suggestion) {
				lines.push(`  - Suggestion: link to \`[[${f.suggestion.target}]]\`` +
					(f.suggestion.alternatives.length
						? ` (also possible: ${f.suggestion.alternatives.map((a) => `\`${a}\``).join(', ')})`
						: ''));
			}
			if (f.detail && f.detail.includes('\n')) {
				for (const d of f.detail.split('\n').slice(0, 10)) lines.push(`  - ${d}`);
			} else if (f.detail) {
				lines.push(`  - ${f.detail}`);
			}
		}
		if (items.length > shown.length) {
			lines.push(`- …and ${items.length - shown.length} more`);
		}
		lines.push('');
	}

	// Attachment inventory
	const exts = Object.entries(stats.attachmentExt).sort((a, b) => b[1].bytes - a[1].bytes);
	if (exts.length > 0) {
		lines.push('## Attachment inventory');
		lines.push('');
		lines.push('| Type | Count | Size |');
		lines.push('| --- | --- | --- |');
		for (const [ext, agg] of exts.slice(0, 15)) {
			lines.push(`| .${ext} | ${agg.count} | ${humanSize(agg.bytes)} |`);
		}
		lines.push('');
	}

	// Biggest files
	if (stats.biggest.length > 0) {
		lines.push('## Largest files');
		lines.push('');
		for (const b of stats.biggest.slice(0, 5)) {
			lines.push(`- \`${b.path}\` — ${humanSize(b.size)}`);
		}
		lines.push('');
	}

	lines.push('---');
	lines.push('*Generated by Vault Doctor. Findings are advisory — review before fixing.*');
	lines.push('');
	return lines.join('\n');
}
